#!/usr/bin/env python3
"""Таблица свёртки латиницы для ключа реестра (нормализатор v1).

Повторяет asciifolding индекса по латинице с диакритикой, лигатурам,
полноширинным знакам, надстрочным и обведённым цифрам, типографским кавычкам
и тире. Кириллица не сворачивается: «й» остаётся «й», как в asciifolding.
Результат — internal/domain/reference/fold_table.go; смена таблицы — новая
версия нормализатора и миграция пересчёта ключей.

    python3 scripts/reference-fold-table.py > internal/domain/reference/fold_table.go
"""

import unicodedata

RANGES = [
    (0x00C0, 0x024F),
    (0x1E00, 0x1EFF),
    (0x2C60, 0x2C7F),
    (0xA720, 0xA7FF),
]
COMPAT_RANGES = [
    (0x2070, 0x209F),
    (0x2460, 0x24FF),
    (0xFB00, 0xFB06),
    (0xFF01, 0xFF5E),
]
MANUAL = {
    "ß": "ss", "ẞ": "ss", "æ": "ae", "Æ": "ae", "œ": "oe", "Œ": "oe",
    "ø": "o", "Ø": "o", "đ": "d", "Đ": "d", "ð": "d", "Ð": "d",
    "ł": "l", "Ł": "l", "þ": "th", "Þ": "th", "ħ": "h", "Ħ": "h",
    "ı": "i", "ŀ": "l", "Ŀ": "l", "ŋ": "n", "Ŋ": "n", "ſ": "s",
    "ƀ": "b", "ƒ": "f", "ǥ": "g", "Ǥ": "g", "ȥ": "z", "Ȥ": "z",
    "ĳ": "ij", "Ĳ": "ij", "ŉ": "'n", "ĸ": "q",
    "‘": "'", "’": "'", "‚": "'", "‛": "'", "′": "'", "‹": "'", "›": "'",
    "“": '"', "”": '"', "„": '"', "‟": '"', "″": '"', "«": '"', "»": '"',
    "‐": "-", "‑": "-", "‒": "-", "–": "-", "—": "-", "―": "-", "⁃": "-",
    "…": "...",
}
PER_LINE = 24


def base(char, form):
    decomposed = unicodedata.normalize(form, char)
    letters = "".join(c for c in decomposed if not unicodedata.combining(c))
    if letters and letters != char and all(ord(c) < 0x80 for c in letters):
        return letters.lower()
    return None


def main():
    table = dict(MANUAL)
    for low, high in RANGES:
        for code in range(low, high + 1):
            char = chr(code)
            if char not in table and (target := base(char, "NFD")):
                table[char] = target
    for low, high in COMPAT_RANGES:
        for code in range(low, high + 1):
            char = chr(code)
            if char not in table and (target := base(char, "NFKD")):
                table[char] = target

    groups = {}
    for char in sorted(table):
        groups.setdefault(table[char], []).append(char)

    print("// Code generated by scripts/reference-fold-table.py; DO NOT EDIT.")
    print()
    print("package reference")
    print()
    print("// foldGroups — замены свёртки v1: ASCII-строка и символы, которые в неё сворачиваются.")
    print("var foldGroups = []foldGroup{")
    for target in sorted(groups):
        chars = groups[target]
        for start in range(0, len(chars), PER_LINE):
            chunk = "".join(chars[start:start + PER_LINE])
            print("\t{to: %s, from: %s}," % (go_string(target), go_string(chunk)))
    print("}")


def go_string(value):
    out = []
    for c in value:
        if c in '"\\':
            out.append("\\" + c)
        elif ord(c) < 0x20 or unicodedata.category(c) in ("Mn", "Me", "Cf", "Zs", "Co", "Cn"):
            out.append("\\u%04x" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


if __name__ == "__main__":
    main()
